// ════════════════════════════════════════════════════════════════
//  عارض نص بتمييز — يحوِّل **نص** إلى غامق بلون ذهبي (تسمية مرحلة/
//  مصطلح رئيسي)، و*نص* إلى مائل بلون ذهبي فاتح (تباين أخف) — بلا أي
//  نجمات حرفية ظاهرة للمستخدم؛ الفقرات مفصولة بسطر فارغ في النص
//  المصدر وتُعرض بمسافة بينها.
// ════════════════════════════════════════════════════════════════
class _RichGuideText extends StatelessWidget {
  const _RichGuideText(this.body);

  final String body;

  static final _emphasisPattern = RegExp(r'\*\*(.+?)\*\*|\*(.+?)\*');

  static List<InlineSpan> _parse(String text, TextStyle base, TextStyle bold, TextStyle italic) {
    final spans = <InlineSpan>[];
    var last = 0;
    for (final m in _emphasisPattern.allMatches(text)) {
      if (m.start > last) {
        spans.add(TextSpan(text: text.substring(last, m.start), style: base));
      }
      final boldContent = m.group(1);
      if (boldContent != null) {
        spans.add(TextSpan(text: boldContent, style: bold));
      } else {
        spans.add(TextSpan(text: m.group(2), style: italic));
      }
      last = m.end;
    }
    if (last < text.length) {
      spans.add(TextSpan(text: text.substring(last), style: base));
    }
    return spans;
  }

  @override
  Widget build(BuildContext context) {
    final base = TextStyle(
      fontFamily: 'Tajawal',
      fontSize: 13.sp,
      color: AppColors.textPrimary,
      height: 1.9,
    );
    final bold = base.copyWith(fontWeight: FontWeight.w700, color: AppColors.goldWarm);
    final italic = base.copyWith(fontStyle: FontStyle.italic, color: AppColors.goldLight);

    final paragraphs = body.trim().split(RegExp(r'\n\s*\n'));

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        for (var i = 0; i < paragraphs.length; i++)
          Padding(
            padding: EdgeInsets.only(bottom: i == paragraphs.length - 1 ? 0 : 12.h),
            child: Text.rich(
              TextSpan(children: _parse(paragraphs[i].trim(), base, bold, italic)),
              textAlign: TextAlign.right,
              textDirection: TextDirection.rtl,
            ),
          ),
      ],
    );
  }
}

